import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const redisPath = require.resolve('redis');
console.log('redis module path:', redisPath);
const pkg = require(redisPath + '/package.json');
console.log('redis package version:', pkg.version);
const client = require(redisPath);
console.log('createClient type:', typeof client.createClient);
const { createClient } = await import('redis');
console.log('imported redis version ok');
const c = createClient({ url: 'redis://localhost:6379', socket: { connectTimeout: 5000 } });
c.on('error', e => { console.error('redis client error', e.message); process.exit(1); });
await c.connect();
console.log('PING', await c.ping());
console.log('HELLO', await c.sendCommand(['HELLO','3']));
await c.quit();
